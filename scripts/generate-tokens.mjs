function normalizeCss(text) {
  return text.replace(/\r\n/g, "\n").replace(/'/g, '"').replace(/\s+/g, " ").trim();
}

/**
 * Main execution
 */
export function run() {
  const brand = loadBrandConfig();
  const css = generateTokensCss(brand);

  if (process.argv.includes("--check")) {
    if (!fs.existsSync(tokensOutputPath)) {
      console.error(`Tokens file missing: ${tokensOutputPath}`);
      process.exit(1);
    }
    const existing = fs.readFileSync(tokensOutputPath, "utf-8");
    if (normalizeCss(existing) !== normalizeCss(css)) {
      console.error("Tokens out of sync! Run `pnpm tokens` to update src/styles/tokens.css.");
      process.exit(1);
    }
    console.log(
      "Tokens check passed: src/styles/tokens.css is in sync with content/site/brand.json."
    );
    return;
  }

  // Ensure output directory exists
  const outputDir = path.dirname(tokensOutputPath);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  fs.writeFileSync(tokensOutputPath, css, "utf-8");
  console.log(`Tokens successfully generated at ${tokensOutputPath}`);
}

// Run if called directly
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  run();
}
