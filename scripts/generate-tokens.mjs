const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");

const brandPath = path.join(rootDir, "content", "site", "brand.json");
const tokensOutputPath = path.join(rootDir, "src", "styles", "tokens.css");

/**
 * Validates and reads content/site/brand.json
 */
export function loadBrandConfig() {
  if (!fs.existsSync(brandPath)) {
    throw new Error(`Brand configuration file not found at ${brandPath}`);
  }

  const raw = fs.readFileSync(brandPath, "utf-8");
  const data = JSON.parse(raw);

  // Validate required structure
  if (!data.name || !data.colors || !data.typography || !data.provenance) {
    throw new Error(
      "Invalid brand.json: missing required name, colors, typography, or provenance."
    );
  }

  return data;
}

